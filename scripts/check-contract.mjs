import { readFileSync } from 'node:fs'
import path from 'node:path'
import openapiTS, { astToString } from 'openapi-typescript'
import { python, root, run } from './lib.mjs'

run(python(), ['backend/scripts/export_openapi.py', '--check'])
const ast = await openapiTS(new URL('../docs/api/openapi.json', import.meta.url))
const expected = '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n' + astToString(ast)
const actual = readFileSync(path.join(root, 'packages/api-contract/src/schema.d.ts'), 'utf8').replaceAll('\r\n', '\n')
if (actual !== expected) {
  console.error('TypeScript contract drift. Run npm run contract:generate after coordinated changes.')
  process.exitCode = 1
} else {
  console.log('Generated TypeScript matches OpenAPI.')
}
